static struct gpio_desc st7102_reset;

static void st7102_480x800_gpio_init(void)
{
    panel_get_gpio(&st7102_reset, ST7102_RESET_PIN);

    panel_gpio_set_value(&st7102_reset, 1);
    aic_delay_ms(120);
    panel_gpio_set_value(&st7102_reset, 0);
    aic_delay_ms(120);
    panel_gpio_set_value(&st7102_reset, 1);
    aic_delay_ms(120);
}

